"""Acquire official DigiFace P1 and extract a reproducible, byte-preserved EDA sample.

Python >=3.10; standard library only. No model, image transforms, or train/test split.
Downloads use resumable 64 MiB ranges; completed chunks are kept until finalization.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import csv
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path, PurePosixPath
import random
import shutil
import time
import urllib.request
import zipfile

URL = "https://facesyntheticspubwedata.z6.web.core.windows.net/wacv-2023/subjects_0-1999_72_imgs.zip"
SIZE = 2938553163
ARCHIVE = "subjects_0-1999_72_imgs.zip"
ROOT = Path(__file__).resolve().parents[1]


def digest(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(4 * 1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def download(target: Path, workers: int):
    if target.exists():
        if target.stat().st_size != SIZE:
            raise RuntimeError("Existing archive has an unexpected size; inspect it before retrying")
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    parts = target.parent / "train_source_download_parts"
    parts.mkdir(exist_ok=True)
    blocksize = 64 * 1024 * 1024
    ranges = [(i, i * blocksize, min(SIZE, (i + 1) * blocksize) - 1)
              for i in range((SIZE + blocksize - 1) // blocksize)]
    # Preserve bytes from an earlier single-connection curl attempt.
    old = target.with_suffix(target.suffix + ".part")
    if old.exists() and old.stat().st_size <= SIZE and not any(parts.glob("*.part")):
        with old.open("rb") as source:
            i = 0
            while data := source.read(blocksize):
                (parts / f"{i:03d}.part").write_bytes(data)
                i += 1
        old.unlink()

    def get_range(item):
        i, start, end = item
        part = parts / f"{i:03d}.part"
        expected = end - start + 1
        for attempt in range(6):
            have = part.stat().st_size if part.exists() else 0
            if have == expected:
                return i, have
            if have > expected:
                raise RuntimeError(f"Oversized chunk {i}")
            request = urllib.request.Request(URL, headers={
                "Range": f"bytes={start + have}-{end}",
                "User-Agent": "CV-course-dataset-acquisition/1.0"})
            try:
                with urllib.request.urlopen(request, timeout=90) as response:
                    wanted = f"bytes {start + have}-{end}/{SIZE}"
                    if response.status != 206 or response.headers.get("Content-Range") != wanted:
                        raise RuntimeError(f"Unexpected range response: {response.status}, {response.headers}")
                    with part.open("ab") as f:
                        shutil.copyfileobj(response, f, length=1024 * 1024)
                if part.stat().st_size != expected:
                    raise OSError(f"Incomplete chunk {i}")
                return i, expected
            except (OSError, TimeoutError) as exc:
                if attempt == 5:
                    raise
                print(f"retry chunk {i}: {type(exc).__name__}", flush=True)
                time.sleep(min(30, 2 ** attempt))

    with ThreadPoolExecutor(max_workers=workers) as pool:
        jobs = [pool.submit(get_range, item) for item in ranges]
        for n, result in enumerate(as_completed(jobs), 1):
            i, count = result.result()
            done = sum(p.stat().st_size for p in parts.glob("*.part"))
            print(f"chunk {i} completed; {n}/{len(ranges)}; bytes {done}/{SIZE}", flush=True)
    combined = target.with_suffix(target.suffix + ".assembled")
    with combined.open("wb") as out:
        for i, _, _ in ranges:
            with (parts / f"{i:03d}.part").open("rb") as source:
                shutil.copyfileobj(source, out, length=4 * 1024 * 1024)
    if combined.stat().st_size != SIZE:
        raise RuntimeError("Assembled size mismatch")
    if not zipfile.is_zipfile(combined):
        raise RuntimeError("Not a ZIP archive")
    combined.rename(target)
    # Only exact chunk files generated by this downloader are removed.
    for i, _, _ in ranges:
        (parts / f"{i:03d}.part").unlink()
    parts.rmdir()


def inventory_extract(archive: Path, per_identity: int, seed: int):
    meta = ROOT / "data_acquisition"
    output = archive.parent / "images_eda"
    output.mkdir(exist_ok=True)
    identities = {}
    with zipfile.ZipFile(archive) as z:
        entries = z.infolist()
        for item in entries:
            if item.is_dir() or not item.filename.lower().endswith((".png", ".jpg", ".jpeg")):
                continue
            path = PurePosixPath(item.filename)
            if ".." in path.parts or path.is_absolute():
                raise RuntimeError("Unsafe archive path")
            # Official layout ends with subj_id/image.png; ignore optional wrapper directory.
            identity = path.parts[-2]
            identities.setdefault(identity, []).append(item)
        with (meta / "train_source_archive_inventory.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["member", "bytes_uncompressed", "bytes_compressed", "crc32", "is_image"])
            for item in entries:
                w.writerow([item.filename, item.file_size, item.compress_size, f"{item.CRC:08x}",
                            int(item.filename.lower().endswith((".png", ".jpg", ".jpeg")))])
        with (meta / "train_source_identity_counts.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["identity", "archive_images", "selected_eda_images"])
            for identity, members in sorted(identities.items()):
                w.writerow([identity, len(members), min(len(members), per_identity)])
        selected = []
        for identity, members in sorted(identities.items()):
            members = sorted(members, key=lambda x: x.filename)
            idseed = int(hashlib.sha256(f"{seed}/{identity}".encode()).hexdigest()[:16], 16)
            chosen = sorted(random.Random(idseed).sample(members, min(per_identity, len(members))),
                            key=lambda x: x.filename)
            for item in chosen:
                destination = output / identity / PurePosixPath(item.filename).name
                destination.parent.mkdir(exist_ok=True)
                # ZipExtFile checks the member CRC while reading. Preserve encoded bytes exactly.
                data = z.read(item)
                if destination.exists() and destination.read_bytes() != data:
                    raise RuntimeError(f"Existing extracted image differs: {destination}")
                if not destination.exists():
                    destination.write_bytes(data)
                selected.append([destination.relative_to(ROOT).as_posix(), identity, item.filename,
                                 len(data), hashlib.sha256(data).hexdigest()])
            if len(selected) % 4000 == 0:
                print(f"extracted {len(selected)} images", flush=True)
    with (meta / "train_source_selected_manifest.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["path", "identity", "archive_member", "bytes", "sha256"])
        w.writerows(selected)
    report = {
        "checked_at_utc": datetime.now(timezone.utc).isoformat(),
        "source": "Microsoft DigiFace-1M official part subjects_0-1999_72_imgs",
        "source_type": "synthetic rendered identities; not collected photographs",
        "url": URL, "expected_server_bytes": SIZE,
        "archive_bytes": archive.stat().st_size, "sha256_local": digest(archive),
        "publisher_checksum_available": False,
        "sha256_note": "Local integrity fingerprint, not publisher-authenticated checksum",
        "archive_members": len(entries), "archive_images": sum(map(len, identities.values())),
        "archive_identities": len(identities), "selected_images": len(selected),
        "selected_identities": len(identities), "per_identity_limit": per_identity, "seed": seed,
        "selection": "per identity deterministic random sample without replacement; no train/test split",
        "extraction": "original encoded image bytes; ZIP member CRC checked for selected files only",
        "unselected_crc_tested": False,
        "output": output.relative_to(ROOT).as_posix(),
        "license": "R-UDA v1.0; non-commercial computational research; retain attribution and downstream terms",
        "casia_status": "Official Drive GET returned quota exceeded HTML; not acquired",
    }
    (meta / "train_source_status.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2), flush=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--per-identity", type=int, default=40)
    p.add_argument("--seed", type=int, default=20261021)
    p.add_argument("--skip-download", action="store_true")
    p.add_argument("--download-only", action="store_true")
    a = p.parse_args()
    if not 1 <= a.workers <= 16 or a.per_identity <= 0:
        p.error("workers must be 1..16; per-identity must be positive")
    target = ROOT / "data/raw/digiface" / ARCHIVE
    if not a.skip_download:
        download(target, a.workers)
    if not a.download_only:
        inventory_extract(target, a.per_identity, a.seed)


if __name__ == "__main__":
    main()
